/**
 * 1) Apply prices from data/bloxdb/precios-para-rellenar.txt
 * 2) Remap case loot skins so each slot keeps ~the OLD skin value
 * 3) Keep case prices unchanged
 * 4) Backup previous DB files into DATABASE ANTIGUA/
 *
 * Localhost only — does not deploy.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PRICE_FILE = path.join(ROOT, 'data', 'bloxdb', 'precios-para-rellenar.txt');
const GENERATED = path.join(ROOT, 'src', 'data', 'skinCatalog.generated.ts');
const CURATED = path.join(ROOT, 'src', 'lib', 'curatedCaseConfig.ts');
const CASE_CATALOG = path.join(ROOT, 'src', 'lib', 'caseCatalog.ts');
const BACKUP_DIR = path.join(ROOT, 'DATABASE ANTIGUA');
const REPORT_PATH = path.join(BACKUP_DIR, 'casos-antes-despues.md');

function normalizeName(name) {
  return String(name || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/globas/g, 'gloves')
    .replace(/[|_/\\:]+/g, ' ')
    .replace(/\bknife\b/g, ' ')
    .replace(/\bm9\b/g, ' ')
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseSkinsTs(filePath) {
  const text = fs.readFileSync(filePath, 'utf8');
  const skins = [];
  const re = /\{\s*id:\s*'([^']+)',\s*name:\s*'((?:\\'|[^'])*)',\s*weapon:\s*'([^']+)',\s*rarity:\s*'([^']+)',\s*wear:\s*'([^']+)',\s*price:\s*(-?\d+(?:\.\d+)?),\s*image:\s*'((?:\\'|[^'])*)'\s*\}/g;
  let m;
  while ((m = re.exec(text))) {
    skins.push({
      id: m[1],
      name: m[2].replace(/\\'/g, "'"),
      weapon: m[3],
      rarity: m[4],
      wear: m[5],
      price: Number(m[6]),
      image: m[7].replace(/\\'/g, "'"),
    });
  }
  return skins;
}

function escapeTs(value) {
  return String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function writeGenerated(skins) {
  const sorted = [...skins].sort((a, b) => {
    const byPrice = Number(b.price) - Number(a.price);
    if (byPrice !== 0) return byPrice;
    return a.name.localeCompare(b.name, 'en');
  });
  const body = `/* AUTO-GENERATED by scripts/apply-prices-and-remap-cases.mjs */
export const GENERATED_SKIN_CATALOG = [
${sorted.map(s =>
    `  { id: '${escapeTs(s.id)}', name: '${escapeTs(s.name)}', weapon: '${escapeTs(s.weapon)}', rarity: '${escapeTs(s.rarity)}', wear: '${escapeTs(s.wear)}', price: ${Number(s.price) || 0}, image: '${escapeTs(s.image)}' },`,
  ).join('\n')}
] as const;
`;
  fs.writeFileSync(GENERATED, body, 'utf8');
}

function parsePriceList(filePath) {
  const lines = fs.readFileSync(filePath, 'utf8').split(/\r?\n/).slice(1).filter(l => l.trim());
  const rows = [];
  for (const line of lines) {
    const m = line.match(/^(.*?)(?:\s*:?\s*(\d+)?)\s*$/);
    let name = (m?.[1] || '').replace(/\s*:\s*$/, '').trim();
    name = name.replace(/\s+Globas\s+\|/i, ' Gloves |');
    // Visión / Vision7 aliases
    if (/mag-7\s*\|\s*visi[oó]n\b/i.test(name) && !/vision7/i.test(name)) {
      name = 'MAG-7 | Vision7';
    }
    const price = m?.[2] != null ? Number(m[2]) : NaN;
    if (!name) continue;
    rows.push({ name, price: Number.isFinite(price) ? price : null, raw: line });
  }
  return rows;
}

function backupFiles(sources) {
  fs.mkdirSync(BACKUP_DIR, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  for (const [name, src] of sources) {
    if (!fs.existsSync(src)) continue;
    fs.copyFileSync(src, path.join(BACKUP_DIR, `${stamp}__${name}`));
    fs.copyFileSync(src, path.join(BACKUP_DIR, `LATEST__${name}`));
  }
  return stamp;
}

function extractCasesFromCurated(text) {
  const cases = [];
  const blockRe = /'([a-z0-9-]+)':\s*\{([\s\S]*?)\n\s*\},/g;
  let m;
  while ((m = blockRe.exec(text))) {
    const slug = m[1];
    const body = m[2];
    if (!body.includes('loot:')) continue;
    const priceM = body.match(/price:\s*(-?\d+(?:\.\d+)?)/);
    const nameM = body.match(/name:\s*'((?:\\'|[^'])*)'/);
    const featuredM = body.match(/featuredSkinId:\s*'([^']+)'/);
    const entries = [...body.matchAll(/\{\s*skinId:\s*'([^']+)',\s*chance:\s*(-?\d+(?:\.\d+)?)\s*\}/g)]
      .map(e => ({ skinId: e[1], chance: Number(e[2]) }));
    if (!entries.length) continue;
    cases.push({
      source: 'curated',
      slug,
      name: nameM ? nameM[1] : slug,
      price: priceM ? Number(priceM[1]) : null,
      featuredSkinId: featuredM?.[1] || entries[0]?.skinId,
      entries,
    });
  }
  return cases;
}

function extractCasesFromGeneratedCatalog(text) {
  const cases = [];
  const caseRe = /\{\s*slug:\s*'([^']+)',\s*name:\s*'((?:\\'|[^'])*)',[\s\S]*?price:\s*(-?\d+(?:\.\d+)?),\s*loot:\s*\{([\s\S]*?)\n\s*\},\s*\n\s*\},/g;
  let m;
  while ((m = caseRe.exec(text))) {
    const slug = m[1];
    const name = m[2];
    const price = Number(m[3]);
    const lootBody = m[4];
    const featuredM = lootBody.match(/featuredSkinId:\s*'([^']+)'/);
    const entries = [...lootBody.matchAll(/\{\s*skinId:\s*'([^']+)',\s*chance:\s*(-?\d+(?:\.\d+)?)\s*\}/g)]
      .map(e => ({ skinId: e[1], chance: Number(e[2]) }));
    cases.push({
      source: 'generated',
      slug,
      name,
      price,
      featuredSkinId: featuredM?.[1] || entries[0]?.skinId,
      entries,
    });
  }
  return cases;
}

function isLootEligible(skin) {
  if (!skin) return false;
  if (skin.weapon === 'Case') return false;
  if (/^case\s*\|/i.test(skin.name)) return false;
  return true;
}

function findClosestSkin(targetPrice, catalog, usedIds = new Set()) {
  // Prefer unused skins so each slot in a case stays unique.
  const unused = catalog.filter(s => !usedIds.has(s.id));
  const pool = unused.length ? unused : catalog;
  let best = null;
  let bestDist = Infinity;
  for (const skin of pool) {
    const dist = Math.abs(Number(skin.price) - Number(targetPrice));
    if (!best || dist < bestDist - 1e-9) {
      best = skin;
      bestDist = dist;
    }
  }
  return best;
}

function remapCase(caseDef, oldById, newCatalog) {
  const eligible = newCatalog.filter(isLootEligible);
  const used = new Set();
  const entryMaps = [];
  const newEntries = caseDef.entries.map(entry => {
    const oldSkin = oldById.get(entry.skinId);
    const targetPrice = oldSkin ? Number(oldSkin.price) : 0;
    const next = findClosestSkin(targetPrice, eligible, used);
    if (next) used.add(next.id);
    entryMaps.push({
      oldSkinId: entry.skinId,
      oldName: oldSkin?.name || entry.skinId,
      oldPrice: targetPrice,
      newSkinId: next?.id || entry.skinId,
      newName: next?.name || entry.skinId,
      newPrice: next ? Number(next.price) : targetPrice,
      chance: entry.chance,
      dist: next ? Math.abs(Number(next.price) - targetPrice) : 0,
    });
    return { skinId: next?.id || entry.skinId, chance: entry.chance };
  });

  const featuredOld = caseDef.featuredSkinId;
  const featuredMap = entryMaps.find(e => e.oldSkinId === featuredOld) || entryMaps[0];
  return {
    ...caseDef,
    featuredSkinId: featuredMap?.newSkinId || caseDef.featuredSkinId,
    entries: newEntries,
    entryMaps,
  };
}

function applySkinIdReplacementsInFile(filePath, caseRemaps, mode) {
  let text = fs.readFileSync(filePath, 'utf8');

  if (mode === 'curated') {
    for (const remapped of caseRemaps.filter(c => c.source === 'curated')) {
      const idMap = new Map(remapped.entryMaps.map(e => [e.oldSkinId, e.newSkinId]));
      const blockRe = new RegExp(`('${remapped.slug}':\\s*\\{)([\\s\\S]*?)(\\n\\s*\\},)`);
      text = text.replace(blockRe, (_full, start, body, end) => {
        let next = body;
        for (const [oldId, newId] of idMap) {
          if (oldId === newId) continue;
          next = next.split(`'${oldId}'`).join(`'${newId}'`);
        }
        return start + next + end;
      });
    }
  } else {
    for (const remapped of caseRemaps) {
      const idMap = new Map(remapped.entryMaps.map(e => [e.oldSkinId, e.newSkinId]));
      const blockRe = new RegExp(
        `(slug:\\s*'${remapped.slug}',[\\s\\S]*?loot:\\s*\\{)([\\s\\S]*?)(\\n\\s*\\},\\s*\\n\\s*\\},)`,
      );
      text = text.replace(blockRe, (_full, start, body, end) => {
        let next = body;
        for (const [oldId, newId] of idMap) {
          if (oldId === newId) continue;
          next = next.split(`'${oldId}'`).join(`'${newId}'`);
        }
        return start + next + end;
      });
    }
  }

  fs.writeFileSync(filePath, text, 'utf8');
}

function formatCaseReport(after) {
  const lines = [];
  lines.push(`### ${after.name} (\`${after.slug}\`)`);
  lines.push(`- Precio caja: **${after.price}** (sin cambio)`);
  lines.push('');
  lines.push('| # | Antes | Precio ant. | Después | Precio nuevo | Chance | Δ |');
  lines.push('|---|-------|-------------|---------|--------------|--------|---|');
  after.entryMaps.forEach((e, i) => {
    lines.push(
      `| ${i + 1} | ${e.oldName} | ${e.oldPrice} | ${e.newName} | ${e.newPrice} | ${e.chance} | ${e.dist} |`,
    );
  });
  lines.push('');
  return lines.join('\n');
}

function findSkinByName(byNorm, name) {
  const key = normalizeName(name);
  if (byNorm.has(key)) return byNorm.get(key);
  const soft = key.replace(/^package\s+/, '');
  for (const [k, skin] of byNorm) {
    const ks = k.replace(/^package\s+/, '');
    if (k === soft || ks === soft || ks === key) return skin;
  }
  return null;
}

function main() {
  if (!fs.existsSync(PRICE_FILE)) throw new Error(`Missing ${PRICE_FILE}`);

  // Prefer pristine pre-price catalog from previous backup if present
  const pristineGenerated = path.join(BACKUP_DIR, 'LATEST__skinCatalog.generated.ts');
  const pristineCurated = path.join(BACKUP_DIR, 'LATEST__curatedCaseConfig.ts');
  const pristineCatalog = path.join(BACKUP_DIR, 'LATEST__caseCatalog.ts');

  // Restore case files from pristine backup before remapping (idempotent)
  if (fs.existsSync(pristineCurated)) fs.copyFileSync(pristineCurated, CURATED);
  if (fs.existsSync(pristineCatalog)) fs.copyFileSync(pristineCatalog, CASE_CATALOG);

  const sourceGenerated = fs.existsSync(pristineGenerated) ? pristineGenerated : GENERATED;
  const oldSkins = parseSkinsTs(sourceGenerated).map(s => ({ ...s }));
  const oldById = new Map(oldSkins.map(s => [s.id, { ...s }]));
  const oldByNorm = new Map(oldSkins.map(s => [normalizeName(s.name), s]));

  // Backup CURRENT working trees as ORIGINAL snapshot if not already stamped for this run
  const stamp = backupFiles([
    ['skinCatalog.generated.ts', sourceGenerated],
    ['curatedCaseConfig.ts', CURATED],
    ['caseCatalog.ts', CASE_CATALOG],
    ['precios-para-rellenar.txt', PRICE_FILE],
  ]);
  console.log(`[remap] backup -> DATABASE ANTIGUA/ (${stamp})`);
  console.log(`[remap] old-price source: ${path.relative(ROOT, sourceGenerated)}`);

  // Apply notepad prices onto a FRESH copy
  const newSkins = oldSkins.map(s => ({ ...s }));
  const newByNorm = new Map(newSkins.map(s => [normalizeName(s.name), s]));

  const priceRows = parsePriceList(PRICE_FILE);
  let updated = 0;
  const unmatched = [];
  for (const row of priceRows) {
    if (row.price == null) {
      unmatched.push({ ...row, reason: 'empty_price' });
      continue;
    }
    const skin = findSkinByName(newByNorm, row.name);
    if (!skin) {
      unmatched.push({ ...row, reason: 'not_found' });
      continue;
    }
    if (skin.price !== row.price) {
      skin.price = row.price;
      updated += 1;
    }
  }

  writeGenerated(newSkins);
  console.log(`[remap] prices updated=${updated} unmatched=${unmatched.length}`);

  // Verify old prices untouched
  const sakuraOld = oldById.get('skin_158_ak_47_sakura');
  const sakuraNew = newSkins.find(s => s.id === 'skin_158_ak_47_sakura');
  console.log(`[remap] check Sakura old=${sakuraOld?.price} new=${sakuraNew?.price}`);

  const curatedText = fs.readFileSync(CURATED, 'utf8');
  const catalogText = fs.readFileSync(CASE_CATALOG, 'utf8');
  const curatedCases = extractCasesFromCurated(curatedText);
  const generatedCases = extractCasesFromGeneratedCatalog(catalogText);

  const curatedSlugs = new Set(curatedCases.map(c => c.slug));
  const effectiveBefore = [
    ...curatedCases,
    ...generatedCases.filter(c => !curatedSlugs.has(c.slug)),
  ].sort((a, b) => a.slug.localeCompare(b.slug));

  const remapped = effectiveBefore.map(c => remapCase(c, oldById, newSkins));
  const allGeneratedRemaps = generatedCases.map(c => remapCase(c, oldById, newSkins));

  applySkinIdReplacementsInFile(CURATED, remapped, 'curated');
  applySkinIdReplacementsInFile(
    CASE_CATALOG,
    allGeneratedRemaps.map(c => ({ ...c, source: 'generated' })),
    'generated',
  );

  const changedSlots = remapped.reduce(
    (n, c) => n + c.entryMaps.filter(e => e.oldSkinId !== e.newSkinId).length,
    0,
  );
  console.log(`[remap] cases=${remapped.length} slots_changed=${changedSlots}`);

  const report = [];
  report.push('# Casos: antes y después del remap de skins');
  report.push('');
  report.push(`Fecha: ${new Date().toISOString()}`);
  report.push(`Backup: \`DATABASE ANTIGUA/\` stamp \`${stamp}\``);
  report.push(`Precios de skins actualizados: **${updated}**`);
  report.push(`Casos remapeados: **${remapped.length}**`);
  report.push(`Slots de loot cambiados: **${changedSlots}**`);
  report.push('');
  report.push('Regla: se mantiene el **precio de la caja**. Cada slot busca la skin cuyo **precio nuevo** esté más cerca del **precio antiguo** de la skin anterior.');
  report.push('');
  for (const c of remapped) report.push(formatCaseReport(c));
  if (unmatched.length) {
    report.push('## Precios no aplicados');
    report.push('');
    for (const u of unmatched) report.push(`- \`${u.raw}\` → ${u.reason}`);
    report.push('');
  }
  fs.writeFileSync(REPORT_PATH, report.join('\n'), 'utf8');
  console.log(`[remap] report -> ${REPORT_PATH}`);

  console.log('\n========== RESUMEN CASOS ==========\n');
  for (const c of remapped) {
    console.log(`## ${c.name} (${c.slug}) — caja ${c.price}`);
    for (const e of c.entryMaps) {
      const mark = e.oldSkinId !== e.newSkinId ? '→' : '=';
      console.log(`  ${e.oldName} (${e.oldPrice}) ${mark} ${e.newName} (${e.newPrice}) [${e.chance}%]`);
    }
    console.log('');
  }
  if (unmatched.length) {
    console.log('Unmatched prices:', unmatched.map(u => `${u.raw} (${u.reason})`).join(' | '));
  }
}

main();
